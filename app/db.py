def get_recent_consultation_texts(limit: int = 500) -> list[str]:
    """Return decrypted consultation bodies for similarity checking only."""
    from .consultation import consultation_text

    texts: list[str] = []
    with ENGINE.connect() as conn:
        rows = conn.execute(
            text("SELECT result_json FROM assessments ORDER BY created_at DESC LIMIT :limit"),
            {"limit": max(1, min(int(limit), 500))},
        ).fetchall()

    for row in rows:
        try:
            result = decrypt_json(row._mapping["result_json"])
            consultation = result.get("_consultation") if isinstance(result, dict) else None
            if consultation:
                body = consultation_text(consultation)
                if body:
                    texts.append(body)
        except Exception:
            continue
    return texts


def delete_personal_data(purchase_id: int) -> dict:
    """Delete consultation data and revoke the entitlement while retaining the transaction."""
    with ENGINE.begin() as conn:
        feedback_deleted = conn.execute(
            text("DELETE FROM feedback WHERE purchase_id=:pid"),
            {"pid": purchase_id},
        ).rowcount or 0
        assessments_deleted = conn.execute(
            text("DELETE FROM assessments WHERE purchase_id=:pid"),
            {"pid": purchase_id},
        ).rowcount or 0
        drafts_deleted = conn.execute(
            text("DELETE FROM assessment_drafts WHERE purchase_id=:pid"),
            {"pid": purchase_id},
        ).rowcount or 0
        conn.execute(
            text(
                """
                UPDATE purchases
                SET email=NULL,
                    acquisition_json='{}',
                    access_revoked_at=:revoked,
                    access_revoked_reason='customer_deleted'
                WHERE id=:pid
                """
            ),
            {"pid": purchase_id, "revoked": now_iso()},
        )
    return {
        "feedback_deleted": feedback_deleted,
        "assessments_deleted": assessments_deleted,
        "drafts_deleted": drafts_deleted,
    }


def admin_summary() -> dict:
    with ENGINE.connect() as conn:
        p = conn.execute(
            text(
                """
                SELECT
                  COUNT(*) AS total,
                  SUM(CASE WHEN status='paid' THEN 1 ELSE 0 END) AS paid,
                  SUM(CASE WHEN status='refunded' THEN 1 ELSE 0 END) AS refunded,
                  SUM(CASE WHEN status='disputed' THEN 1 ELSE 0 END) AS disputed,
                  SUM(CASE WHEN status='paid' THEN amount_cents ELSE 0 END) AS revenue_cents
                FROM purchases
                """
            )
        ).fetchone()
        a = conn.execute(text("SELECT COUNT(*) AS total FROM assessments")).fetchone()
        f = conn.execute(
            text("SELECT day, COUNT(*) AS c FROM feedback GROUP BY day ORDER BY day")
        ).fetchall()

    pm = p._mapping
    total = pm["total"] or 0
    paid = pm["paid"] or 0
    assessments = a._mapping["total"] or 0
    return {
        "purchases": total,
        "paid": paid,
        "refunded": pm["refunded"] or 0,
        "disputed": pm["disputed"] or 0,
        "revenue_cents": pm["revenue_cents"] or 0,
        "assessment_completions": assessments,
        "paid_to_assessment_rate": round((assessments / paid * 100), 1) if paid else 0,
        "feedback": {str(row._mapping["day"]): row._mapping["c"] for row in f},
    }
