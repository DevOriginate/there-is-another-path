def privacy_maintenance(retention_days: int) -> dict:
    """Encrypt legacy rows, scrub local contact data, and expire private content."""
    cutoff = (datetime.now(timezone.utc) - timedelta(days=retention_days)).isoformat()
    encrypted = 0
    with ENGINE.begin() as conn:
        rows = conn.execute(
            text("SELECT id, answers_json, result_json FROM assessments")
        ).fetchall()
        for row in rows:
            m = row._mapping
            answers_raw = m["answers_json"]
            result_raw = m["result_json"]
            if not str(answers_raw).startswith("fernet:") or not str(result_raw).startswith("fernet:"):
                conn.execute(
                    text(
                        "UPDATE assessments SET answers_json=:answers, result_json=:result WHERE id=:id"
                    ),
                    {
                        "answers": encrypt_json(decrypt_json(answers_raw)),
                        "result": encrypt_json(decrypt_json(result_raw)),
                        "id": m["id"],
                    },
                )
                encrypted += 1

        feedback_rows = conn.execute(
            text("SELECT id, payload_json FROM feedback")
        ).fetchall()
        for row in feedback_rows:
            m = row._mapping
            raw = m["payload_json"]
            if not str(raw).startswith("fernet:"):
                conn.execute(
                    text("UPDATE feedback SET payload_json=:payload WHERE id=:id"),
                    {"payload": encrypt_json(json.loads(raw)), "id": m["id"]},
                )

        draft_rows = conn.execute(
            text("SELECT purchase_id, answers_json FROM assessment_drafts")
        ).fetchall()
        for row in draft_rows:
            m = row._mapping
            raw = m["answers_json"]
            if not str(raw).startswith("fernet:"):
                conn.execute(
                    text(
                        "UPDATE assessment_drafts SET answers_json=:answers WHERE purchase_id=:pid"
                    ),
                    {
                        "answers": encrypt_json(json.loads(raw)),
                        "pid": m["purchase_id"],
                    },
                )

        token_rows = conn.execute(
            text("SELECT id, access_token FROM purchases")
        ).fetchall()
        legacy_tokens_hashed = 0
        for row in token_rows:
            m = row._mapping
            token_value = str(m["access_token"])
            if not token_value.startswith("sha256:"):
                conn.execute(
                    text("UPDATE purchases SET access_token=:digest WHERE id=:id"),
                    {"digest": _token_digest(token_value), "id": m["id"]},
                )
                legacy_tokens_hashed += 1

        scrubbed = conn.execute(
            text("UPDATE purchases SET email=NULL WHERE email IS NOT NULL")
        ).rowcount or 0

        # Expiration is tied to the purchase window, not to the day the report happened to be generated.
        expired_ids = conn.execute(
            text(
                """
                SELECT id FROM purchases
                WHERE COALESCE(paid_at,created_at) < :cutoff
                """
            ),
            {"cutoff": cutoff},
        ).fetchall()
        ids = [row._mapping["id"] for row in expired_ids]

        feedback_deleted = assessments_deleted = drafts_deleted = 0
        for purchase_id in ids:
            feedback_deleted += conn.execute(
                text("DELETE FROM feedback WHERE purchase_id=:pid"),
                {"pid": purchase_id},
            ).rowcount or 0
            assessments_deleted += conn.execute(
                text("DELETE FROM assessments WHERE purchase_id=:pid"),
                {"pid": purchase_id},
            ).rowcount or 0
            drafts_deleted += conn.execute(
                text("DELETE FROM assessment_drafts WHERE purchase_id=:pid"),
                {"pid": purchase_id},
            ).rowcount or 0

    return {
        "legacy_assessments_encrypted": encrypted,
        "legacy_access_tokens_hashed": legacy_tokens_hashed,
        "purchase_emails_scrubbed": scrubbed,
        "expired_feedback_deleted": feedback_deleted,
        "expired_assessments_deleted": assessments_deleted,
        "expired_drafts_deleted": drafts_deleted,
    }


