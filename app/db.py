def mark_paid_by_session(session_id: str, payment_intent_id: str | None = None):
    # Webhook retries must not extend the access window or reactivate refunds/disputes.
    with ENGINE.begin() as conn:
        conn.execute(
            text(
                """
                UPDATE purchases
                SET status=CASE WHEN status='pending' THEN 'paid' ELSE status END,
                    paid_at=COALESCE(paid_at,:paid),
                    email=NULL,
                    stripe_payment_intent_id=COALESCE(:pi,stripe_payment_intent_id)
                WHERE stripe_session_id=:sid
                """
            ),
            {"paid": now_iso(), "sid": session_id, "pi": payment_intent_id},
        )


def recover_paid_purchase(
    session_id: str,
    access_token: str | None,
    amount_cents: int,
    currency: str = "usd",
    email: str | None = None,
    payment_intent_id: str | None = None,
) -> dict | None:
    paid = now_iso()
    access_token = access_token or secrets.token_urlsafe(24)
    params = {
        "sid": session_id,
        "pi": payment_intent_id,
        "token": _token_digest(access_token),
        "amount": amount_cents,
        "currency": currency or "usd",
        "created": paid,
        "paid": paid,
    }
    with ENGINE.begin() as conn:
        by_session = conn.execute(
            text("SELECT id,status FROM purchases WHERE stripe_session_id=:sid"),
            {"sid": session_id},
        ).fetchone()
        if by_session:
            conn.execute(
                text(
                    """
                    UPDATE purchases
                    SET status=CASE WHEN status='pending' THEN 'paid' ELSE status END,
                        paid_at=COALESCE(paid_at,:paid),
                        email=NULL,
                        amount_cents=:amount,
                        currency=:currency,
                        stripe_payment_intent_id=COALESCE(:pi,stripe_payment_intent_id)
                    WHERE stripe_session_id=:sid
                    """
                ),
                params,
            )
        else:
            by_token = conn.execute(
                text("SELECT id,status FROM purchases WHERE access_token=:token"),
                {"token": _token_digest(access_token)},
            ).fetchone()
            if by_token:
                conn.execute(
                    text(
                        """
                        UPDATE purchases
                        SET stripe_session_id=:sid,
                            status=CASE WHEN status='pending' THEN 'paid' ELSE status END,
                            paid_at=COALESCE(paid_at,:paid),
                            email=NULL,
                            amount_cents=:amount,
                            currency=:currency,
                            stripe_payment_intent_id=COALESCE(:pi,stripe_payment_intent_id)
                        WHERE access_token=:token
                        """
                    ),
                    params,
                )
            else:
                conn.execute(
                    text(
                        """
                        INSERT INTO purchases(
                          access_token,email,status,amount_cents,currency,
                          stripe_session_id,stripe_payment_intent_id,
                          acquisition_json,created_at,paid_at
                        )
                        VALUES(:token,NULL,'paid',:amount,:currency,:sid,:pi,'{}',:created,:paid)
                        """
                    ),
                    params,
                )
    return get_purchase_by_session(session_id) or get_purchase_by_token(access_token)


def get_purchase_by_token(token: str) -> Optional[dict]:
    digest = _token_digest(token)
    with ENGINE.begin() as conn:
        row = conn.execute(
            text("SELECT * FROM purchases WHERE access_token=:digest OR access_token=:legacy"),
            {"digest": digest, "legacy": token},
        ).fetchone()
        if row and row._mapping["access_token"] == token:
            conn.execute(
                text("UPDATE purchases SET access_token=:digest WHERE id=:id"),
                {"digest": digest, "id": row._mapping["id"]},
            )
            row = conn.execute(
                text("SELECT * FROM purchases WHERE id=:id"),
                {"id": row._mapping["id"]},
            ).fetchone()
    return _rowdict(row)


