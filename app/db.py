def get_purchases_by_ids(purchase_ids: list[int]) -> list[dict]:
    ids = [int(pid) for pid in purchase_ids if int(pid) > 0]
    if not ids:
        return []
    placeholders = ",".join(f":p{i}" for i in range(len(ids)))
    params = {f"p{i}": pid for i, pid in enumerate(ids)}
    with ENGINE.connect() as conn:
        rows = conn.execute(
            text(f"SELECT * FROM purchases WHERE id IN ({placeholders}) ORDER BY paid_at DESC, id DESC"),
            params,
        ).fetchall()
    return [_rowdict(row) for row in rows]


