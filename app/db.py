class DuplicateConsultationFingerprint(RuntimeError):
    pass


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _token_digest(token: str) -> str:
    return "sha256:" + hashlib.sha256(token.encode("utf-8")).hexdigest()


def _normalize_db_url(url: str) -> str:
    if url.startswith("postgres://"):
        return "postgresql+psycopg://" + url[len("postgres://"):]
    if url.startswith("postgresql://") and "+" not in url.split("://", 1)[0]:
        return "postgresql+psycopg://" + url[len("postgresql://"):]
    return url


DB_URL = _normalize_db_url(DATABASE_URL)
_engine_kwargs: dict[str, Any] = {"pool_pre_ping": True}
if DB_URL.startswith("sqlite:"):
    _engine_kwargs["connect_args"] = {"check_same_thread": False}
ENGINE: Engine = create_engine(DB_URL, **_engine_kwargs)


def connect():
    return ENGINE.begin()


def _ensure_purchase_columns() -> None:
    columns = {col["name"] for col in inspect(ENGINE).get_columns("purchases")}
    additions = {
        "stripe_payment_intent_id": "TEXT",
        "access_revoked_at": "TEXT",
        "access_revoked_reason": "TEXT",
    }
    for name, ddl in additions.items():
        if name in columns:
            continue
        with ENGINE.begin() as conn:
            conn.execute(text(f"ALTER TABLE purchases ADD COLUMN {name} {ddl}"))


def init_db():
    statements = [
        """CREATE TABLE IF NOT EXISTS purchases (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          access_token TEXT UNIQUE NOT NULL,
          email TEXT,
          status TEXT NOT NULL DEFAULT 'pending',
          amount_cents INTEGER NOT NULL,
          currency TEXT NOT NULL DEFAULT 'usd',
          stripe_session_id TEXT UNIQUE,
          stripe_payment_intent_id TEXT,
          access_revoked_at TEXT,
          access_revoked_reason TEXT,
          acquisition_json TEXT NOT NULL DEFAULT '{}',
          created_at TEXT NOT NULL,
          paid_at TEXT
        )""",
        """CREATE TABLE IF NOT EXISTS assessments (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          purchase_id INTEGER NOT NULL UNIQUE,
          answers_json TEXT NOT NULL,
          result_json TEXT NOT NULL,
          created_at TEXT NOT NULL,
          FOREIGN KEY(purchase_id) REFERENCES purchases(id)
        )""",
        """CREATE TABLE IF NOT EXISTS feedback (
          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          purchase_id INTEGER NOT NULL,
          day INTEGER NOT NULL,
          payload_json TEXT NOT NULL,
          created_at TEXT NOT NULL,
          UNIQUE(purchase_id, day),
          FOREIGN KEY(purchase_id) REFERENCES purchases(id)
        )""",
        """CREATE TABLE IF NOT EXISTS assessment_drafts (
          purchase_id INTEGER PRIMARY KEY,
          answers_json TEXT NOT NULL,
          current_index INTEGER NOT NULL DEFAULT 0,
          updated_at TEXT NOT NULL,
          FOREIGN KEY(purchase_id) REFERENCES purchases(id)
        )""",
        """CREATE TABLE IF NOT EXISTS consultation_fingerprints (
          fingerprint TEXT PRIMARY KEY,
          created_at TEXT NOT NULL
        )""",
        """CREATE TABLE IF NOT EXISTS consultation_fragment_fingerprints (
          fingerprint TEXT PRIMARY KEY,
          created_at TEXT NOT NULL
        )""",
        "CREATE INDEX IF NOT EXISTS idx_purchase_status ON purchases(status)",
        "CREATE INDEX IF NOT EXISTS idx_purchase_created ON purchases(created_at)",
        "CREATE INDEX IF NOT EXISTS idx_purchase_payment_intent ON purchases(stripe_payment_intent_id)",
    ]
    if DB_URL.startswith("sqlite:"):
        for idx in range(3):
            statements[idx] = statements[idx].replace(
                "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                "INTEGER PRIMARY KEY AUTOINCREMENT",
            )

    with ENGINE.begin() as conn:
        for stmt in statements[:-1]:
            conn.execute(text(stmt))

    _ensure_purchase_columns()

    # Index creation must happen after legacy tables receive the new column.
    with ENGINE.begin() as conn:
        conn.execute(text(statements[-1]))


def _rowdict(row) -> dict | None:
    return dict(row._mapping) if row else None


def create_purchase(
    amount_cents: int,
    acquisition: dict[str, Any],
    email: str | None = None,
    status: str = "pending",
    currency: str = "usd",
) -> dict:
    token = secrets.token_urlsafe(24)
    created = now_iso()
    params = {
        "token": _token_digest(token),
        "email": email,
        "status": status,
        "amount": amount_cents,
        "currency": (currency or "usd").lower(),
        "acq": json.dumps(acquisition),
        "created": created,
        "paid": created if status == "paid" else None,
    }
    with ENGINE.begin() as conn:
        if DB_URL.startswith("sqlite:"):
            res = conn.execute(
                text(
                    "INSERT INTO purchases(access_token,email,status,amount_cents,currency,acquisition_json,created_at,paid_at) "
                    "VALUES(:token,:email,:status,:amount,:currency,:acq,:created,:paid)"
                ),
                params,
            )
            pid = res.lastrowid
        else:
            pid = conn.execute(
                text(
                    "INSERT INTO purchases(access_token,email,status,amount_cents,currency,acquisition_json,created_at,paid_at) "
                    "VALUES(:token,:email,:status,:amount,:currency,:acq,:created,:paid) RETURNING id"
                ),
                params,
            ).scalar_one()
    return {"id": pid, "access_token": token, "status": status}


