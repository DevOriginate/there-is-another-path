def save_assessment(
    purchase_id: int,
    answers: dict,
    result: dict,
    consultation_fingerprint: str | None = None,
    consultation_fragment_fingerprints: list[str] | None = None,
):
    params = {
        "pid": purchase_id,
        "answers": encrypt_json(answers),
        "result": encrypt_json(result),
        "created": now_iso(),
    }
    with ENGINE.begin() as conn:
        existing = conn.execute(
            text("SELECT 1 FROM assessments WHERE purchase_id=:pid"),
            {"pid": purchase_id},
        ).fetchone()
        if existing:
            raise RuntimeError("Assessment already completed for this purchase")

        if consultation_fingerprint:
            inserted = conn.execute(
                text(
                    "INSERT INTO consultation_fingerprints(fingerprint,created_at) "
                    "VALUES(:fp,:created) ON CONFLICT(fingerprint) DO NOTHING"
                ),
                {"fp": consultation_fingerprint, "created": params["created"]},
            ).rowcount
            if not inserted:
                raise DuplicateConsultationFingerprint(
                    "Consultation content fingerprint already exists"
                )

        for fragment_fp in dict.fromkeys(consultation_fragment_fingerprints or []):
            inserted = conn.execute(
                text(
                    "INSERT INTO consultation_fragment_fingerprints(fingerprint,created_at) "
                    "VALUES(:fp,:created) ON CONFLICT(fingerprint) DO NOTHING"
                ),
                {"fp": fragment_fp, "created": params["created"]},
            ).rowcount
            if not inserted:
                raise DuplicateConsultationFingerprint(
                    "Consultation section fingerprint already exists"
                )

        conn.execute(
            text(
                "INSERT INTO assessments(purchase_id,answers_json,result_json,created_at) "
                "VALUES(:pid,:answers,:result,:created)"
            ),
            params,
        )
        conn.execute(
            text("DELETE FROM assessment_drafts WHERE purchase_id=:pid"),
            {"pid": purchase_id},
        )


def get_assessment_for_purchase(purchase_id: int) -> Optional[dict]:
    with ENGINE.connect() as conn:
        row = conn.execute(
            text("SELECT * FROM assessments WHERE purchase_id=:pid"),
            {"pid": purchase_id},
        ).fetchone()
    if not row:
        return None
    data = _rowdict(row)
    data["answers"] = decrypt_json(data.pop("answers_json"))
    data["result"] = decrypt_json(data.pop("result_json"))
    return data


def save_assessment_draft(purchase_id: int, answers: dict, current_index: int):
    params = {
        "pid": purchase_id,
        "answers": encrypt_json(answers),
        "idx": max(0, int(current_index)),
        "updated": now_iso(),
    }
    with ENGINE.begin() as conn:
        if DB_URL.startswith("sqlite:"):
            conn.execute(
                text(
                    """
                    INSERT INTO assessment_drafts(purchase_id,answers_json,current_index,updated_at)
                    VALUES(:pid,:answers,:idx,:updated)
                    ON CONFLICT(purchase_id) DO UPDATE SET
                      answers_json=excluded.answers_json,
                      current_index=excluded.current_index,
                      updated_at=excluded.updated_at
                    """
                ),
                params,
            )
        else:
            conn.execute(
                text(
                    """
                    INSERT INTO assessment_drafts(purchase_id,answers_json,current_index,updated_at)
                    VALUES(:pid,:answers,:idx,:updated)
                    ON CONFLICT(purchase_id) DO UPDATE SET
                      answers_json=EXCLUDED.answers_json,
                      current_index=EXCLUDED.current_index,
                      updated_at=EXCLUDED.updated_at
                    """
                ),
                params,
            )


